// Generates src/phone.css: on phones (max-width 600px) every rule that sets text
// below 12px gets the same selector with font-size 12px. The desktop console was
// designed at 6–9px labels, which are unreadable on a phone. Run after editing
// the console stylesheets:  node scripts/phone-type.cjs
const fs = require("fs");
const path = require("path");
const postcss = require("postcss");

const root = path.resolve(__dirname, "..", "src");
const FLOOR = 12;
const files = [];
const walk = (dir) => {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else if (name.endsWith(".css") && name !== "phone.css") files.push(full);
  }
};
walk(root);
files.sort();

let body = "";
let count = 0;
for (const file of files) {
  const css = fs.readFileSync(file, "utf8");
  const ast = postcss.parse(css, { from: file });
  const lines = [];
  ast.walkRules((rule) => {
    if (rule.parent && rule.parent.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
    const small = [];
    rule.walkDecls(/^font-size$/, (d) => {
      const m = d.value.match(/^(\d+(?:\.\d+)?)px$/);
      if (m && parseFloat(m[1]) < FLOOR) small.push(d);
    });
    if (!small.length) return;
    const important = small.some((d) => d.important);
    lines.push(`${rule.selector} { font-size: ${FLOOR}px${important ? " !important" : ""}; }`);
    count += 1;
  });
  if (lines.length) {
    body += `  /* ${path.relative(root, file)} */\n`;
    body += lines.map((l) => `  ${l}`).join("\n") + "\n";
  }
}

const out =
  "/* GENERATED by scripts/phone-type.cjs. Do not edit by hand.\n" +
  " * On phones, text that the console sets below 12px is raised to 12px.\n" +
  " * Loaded last, so it wins over the desktop rules with the same selectors. */\n" +
  "@media (max-width: 600px) {\n" +
  body +
  "}\n";
fs.writeFileSync(path.join(root, "phone.css"), out);
console.log(`phone.css: ${count} rules raised to ${FLOOR}px`);
